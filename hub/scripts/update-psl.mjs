#!/usr/bin/env node
/**
 * Reproducible Mozilla Public Suffix List Updater (`hub/scripts/update-psl.mjs`).
 *
 * Fetches the canonical Public Suffix List from `https://publicsuffix.org/list/public_suffix_list.dat`
 * (or reads `--input <path>`), normalizes all IDN rules to ASCII/punycode (`xn--...`) via `node:url`
 * `domainToASCII` while preserving ICANN and PRIVATE DOMAINS section markers, and writes:
 *  1. `internal/extract/manifests/public_suffix_list.dat` (embedded in Go via `//go:embed manifests/*`)
 *  2. `hub/src/psl-data.ts` (zero-loader TypeScript module identical to `public_suffix_list.dat`)
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { domainToASCII, fileURLToPath, pathToFileURL } from 'node:url';

export const PSL_SOURCE_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';

const hubRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(hubRoot, '..');
const datOutPath = join(repoRoot, 'internal', 'extract', 'manifests', 'public_suffix_list.dat');
const tsOutPath = join(hubRoot, 'src', 'psl-data.ts');

export function compileCompactPslDat(rawText) {
  const icannRules = [];
  const privateRules = [];
  const seenIcann = new Set();
  const seenPrivate = new Set();

  let section = 'icann';
  for (const rawLine of String(rawText ?? '').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.includes('===BEGIN ICANN DOMAINS===')) {
      section = 'icann';
      continue;
    }
    if (line.includes('===BEGIN PRIVATE DOMAINS===')) {
      section = 'private';
      continue;
    }
    if (line.startsWith('//')) continue;

    const token = line.split(/\s+/)[0].toLowerCase();
    if (!token) continue;

    let normalized = '';
    if (token.startsWith('!')) {
      const ascii = domainToASCII(token.slice(1));
      if (!ascii) continue;
      normalized = `!${ascii}`;
    } else if (token.startsWith('*.')) {
      const ascii = domainToASCII(token.slice(2));
      if (!ascii) continue;
      normalized = `*.${ascii}`;
    } else {
      const ascii = domainToASCII(token);
      if (!ascii) continue;
      normalized = ascii;
    }

    if (section === 'private') {
      if (!seenPrivate.has(normalized)) {
        seenPrivate.add(normalized);
        privateRules.push(normalized);
      }
    } else if (!seenIcann.has(normalized)) {
      seenIcann.add(normalized);
      icannRules.push(normalized);
    }
  }

  if (icannRules.length < 1000 || privateRules.length < 500) {
    throw new Error(
      `Refusing to write truncated PSL (icann=${icannRules.length}, private=${privateRules.length})`,
    );
  }

  return [
    '// Mozilla Public Suffix List (MPL-2.0) — https://publicsuffix.org/list/public_suffix_list.dat',
    '// Generated by: node hub/scripts/update-psl.mjs',
    '// ===BEGIN ICANN DOMAINS===',
    ...icannRules,
    '// ===END ICANN DOMAINS===',
    '// ===BEGIN PRIVATE DOMAINS===',
    ...privateRules,
    '// ===END PRIVATE DOMAINS===',
    '',
  ].join('\n');
}

export function renderPslDataTsModule(compactDat) {
  return [
    '/**',
    ' * Auto-generated from `internal/extract/manifests/public_suffix_list.dat` by `node hub/scripts/update-psl.mjs`.',
    ' * Do not edit manually.',
    ' */',
    `export const PUBLIC_SUFFIX_LIST_DAT = ${JSON.stringify(compactDat)};`,
    '',
  ].join('\n');
}

const isMainModule =
  Boolean(process.argv[1]) &&
  resolve(process.argv[1]).replace(/\\/g, '/').endsWith('/update-psl.mjs') &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isMainModule) {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const onlineCheck = args.includes('--online');
  const inputIdx = args.indexOf('--input');
  const inputPath = inputIdx >= 0 ? args[inputIdx + 1] : null;

  const rawSource = inputPath
    ? readFileSync(resolve(inputPath), 'utf8')
    : checkOnly && !onlineCheck && existsSync(datOutPath)
      ? readFileSync(datOutPath, 'utf8')
      : await (async () => {
          const resp = await fetch(PSL_SOURCE_URL);
          if (!resp.ok) {
            throw new Error(`Failed to fetch ${PSL_SOURCE_URL}: HTTP ${resp.status}`);
          }
          return await resp.text();
        })();

  const compactDat = compileCompactPslDat(rawSource);

  if (checkOnly) {
    const curDat = existsSync(datOutPath) ? readFileSync(datOutPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (curDat !== compactDat) {
      console.error('Vendored PSL file is out of sync. Run: node hub/scripts/update-psl.mjs');
      process.exit(1);
    }
    console.log('✔ Verified vendored public_suffix_list.dat.');
  } else {
    writeFileSync(datOutPath, compactDat, 'utf8');
    console.log(
      `✔ Updated internal/extract/manifests/public_suffix_list.dat (${compactDat.length} bytes)`,
    );
  }
}
